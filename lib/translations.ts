export function getLocalizedTranslations(langCode: string): TranslationDictionary {
  if (TRANSLATIONS[langCode]) {
    return { ...TRANSLATIONS.en, ...TRANSLATIONS[langCode] };
  }

  // Find language info
  const lang = SUPPORTED_LANGUAGES.find((l) => l.code === langCode);
  if (!lang) return TRANSLATIONS.en;

  // Base fallback matching related regional language
  let baseDict = TRANSLATIONS.en;
  if (lang.region.includes('Assam') || lang.region.includes('Bodoland') || lang.region.includes('Dima')) {
    baseDict = TRANSLATIONS.as || TRANSLATIONS.en;
  } else if (lang.region.includes('Manipur')) {
    baseDict = TRANSLATIONS.mni || TRANSLATIONS.en;
  } else if (lang.region.includes('Mizoram')) {
    baseDict = TRANSLATIONS.lus || TRANSLATIONS.en;
  } else if (lang.region.includes('Meghalaya')) {
    baseDict = TRANSLATIONS.kha || TRANSLATIONS.grt || TRANSLATIONS.en;
  } else if (lang.region.includes('Nagaland')) {
    baseDict = TRANSLATIONS.nag || TRANSLATIONS.en;
  } else if (lang.region.includes('Sikkim')) {
    baseDict = TRANSLATIONS.ne || TRANSLATIONS.en;
  } else if (lang.region.includes('Tripura')) {
    baseDict = TRANSLATIONS.trp || TRANSLATIONS.bn || TRANSLATIONS.en;
  }

  return {
    ...TRANSLATIONS.en,
    ...baseDict,
    'nav.languages': lang.nativeName,
    'hero.badge': `${lang.nativeName.toUpperCase()} • NORTH EAST LOGISTICS & ROAD HAZARD INTELLIGENCE`,
  };
}
